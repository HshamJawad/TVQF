(function() {
  const STORAGE_KEY = 'tvqf-lang';

  function getSavedLang() {
    try {
      return localStorage.getItem(STORAGE_KEY);
    } catch (e) {
      return null;
    }
  }

  function saveLang(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) { /* ignore */ }
  }

  function applyLanguage(lang) {
    const dict = TVQF_TRANSLATIONS[lang] || TVQF_TRANSLATIONS.en;

    // Text / HTML content
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    // Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Links (e.g. form download buttons that differ by language)
    document.querySelectorAll('[data-i18n-href]').forEach(function(el) {
      const key = el.getAttribute('data-i18n-href');
      if (dict[key] !== undefined) {
        el.setAttribute('href', dict[key]);
      }
    });

    // Document direction / language / font
    const html = document.documentElement;
    if (lang === 'ar') {
      html.setAttribute('lang', 'ar');
      html.setAttribute('dir', 'rtl');
      document.body.classList.add('lang-ar');
    } else {
      html.setAttribute('lang', 'en');
      html.setAttribute('dir', 'ltr');
      document.body.classList.remove('lang-ar');
    }

    // Toggle button label shows the language you can SWITCH TO
    const toggleLabel = document.getElementById('langToggleLabel');
    if (toggleLabel) {
      toggleLabel.textContent = (lang === 'ar') ? 'EN' : 'AR';
    }
    const toggleBtn = document.getElementById('langToggleBtn');
    if (toggleBtn) {
      toggleBtn.setAttribute('aria-label', (lang === 'ar') ? 'Switch to English' : 'التبديل إلى العربية');
    }

    saveLang(lang);
    window.TVQF_CURRENT_LANG = lang;

    // Re-render the interactive levels table/modal (if present on this page) in the new language
    if (typeof window.renderLevelsTable === 'function') {
      window.renderLevelsTable();
    }
  }

  function toggleLanguage() {
    const current = window.TVQF_CURRENT_LANG || 'en';
    applyLanguage(current === 'ar' ? 'en' : 'ar');
  }

  // Expose for the toggle button and for debugging
  window.toggleLanguage = toggleLanguage;
  window.applyLanguage = applyLanguage;

  document.addEventListener('DOMContentLoaded', function() {
    const initial = getSavedLang() || 'ar';
    applyLanguage(initial);
  });
})();
